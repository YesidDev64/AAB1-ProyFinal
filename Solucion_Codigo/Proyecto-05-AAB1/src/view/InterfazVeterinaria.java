    private void btnAtenderFacturarCitaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtenderFacturarCitaActionPerformed
        // TODO add your handling code here:
        if(txtFNumeroCita.getText().trim().isEmpty() || 
           txtFDiagnostico.getText().trim().isEmpty() ||
           txtFCantidadExamenes.getText().trim().isEmpty() ||  
           txtFCantidadMedicamento.getText().trim().isEmpty()){
            JOptionPane.showMessageDialog(this, 
                    "Campos obligatorios vacios",
                    "Campos Vacios", JOptionPane.WARNING_MESSAGE);
            return;             
        }
        
        try {
            int numCita = Integer.parseInt(txtFNumeroCita.getText().trim()), 
                cantExamenes = Integer.parseInt(txtFCantidadExamenes.getText().trim()), 
                cantMedicamentos = Integer.parseInt(txtFCantidadMedicamento.getText().trim());
            String diagnostico = txtFDiagnostico.getText().trim(), 
                   enfermedad = txtFEnfermedad.getText().trim(), 
                   medicamento = txtFMedicamentos.getText().trim();
            
            if(diagnostico.isEmpty()) diagnostico = "ninguno";
            if(medicamento.isEmpty()) medicamento = "ninguno";
            if(enfermedad.isEmpty()) enfermedad = "ninguno";
            
            if(numCita <= 0 || cantExamenes < 0 || cantMedicamentos < 0){
                JOptionPane.showMessageDialog(this, 
                        "Los valores numericos deben ser positivos",
                        "Valores Invalidos", JOptionPane.WARNING_MESSAGE);
                return;                 
            }
            
            String resultado = clinica.atenderCita(numCita, diagnostico, enfermedad, 
                                                   cantExamenes, medicamento, cantMedicamentos);
            txtResultadosFacturacion.setText(resultado);
            
            txtFNumeroCita.setText("");
            txtFCantidadExamenes.setText("");
            txtFCantidadMedicamento.setText("");
            txtFDiagnostico.setText("");
            txtFEnfermedad.setText("");
            txtFMedicamentos.setText("");    
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, 
                    "Numero de citas, examenes y su cantidad deben ser numeros enteros",
                    "Formato incorrecto", JOptionPane.ERROR_MESSAGE);             
        }
    }//GEN-LAST:event_btnAtenderFacturarCitaActionPerformed

